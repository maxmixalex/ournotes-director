using System.Diagnostics;
using System.Security.Cryptography;
using System.Text.Json.Nodes;
using OurNotes.Director.Core;

/// <summary>Measures native antialias coverage before encoding and actual CineForm
/// decoded RGBA afterwards. Sampling error and codec error are reported separately.</summary>
static class GraphicsQualityNativeTests
{
    public static int Run(string directory, string ffmpeg)
    {
        directory = Path.GetFullPath(directory); Directory.CreateDirectory(directory);
        var checks = new JsonArray(); var comparisons = new JsonArray();
        var report = new JsonObject { ["ok"] = false, ["checks"] = checks, ["comparisons"] = comparisons,
            ["comparison"] = "RGBA8 premultiplied colour and alpha; sampling loss is separate from codec loss" };
        void Check(bool value, string name)
        {
            checks.Add((JsonNode)new JsonObject { ["name"] = name, ["ok"] = value });
            if (!value) throw new InvalidOperationException(name);
            Console.WriteLine(name);
        }
        try
        {
            NativeTestGraphics.Configure();
            report["ffmpegVersion"] = Media.Run(ffmpeg, ["-version"]).Split('\n')[0].TrimEnd();
            const int width = 96, height = 96;
            var geometry = new Dictionary<int, Pixels[]>();
            foreach (int sampling in new[] { 1, 4 })
            {
                using var gl = new OffscreenGl(width * sampling, height * sampling); report["device"] = gl.Device;
                uint white = gl.Upload(new(1, 1, [255, 255, 255, 255]));
                var frames = new Pixels[2];
                for (int frame = 0; frame < frames.Length; frame++)
                {
                    gl.Begin([0, 0, 0, 0]); float shift = frame * .123f;
                    gl.Draw(white, [-.873f + shift, -.764f, .718f + shift, -.613f, -.097f + shift, .846f],
                        [0, 0, 1, 0, .5f, 1], [0, 1, 2], 1, [1, 1, 1, 1], [0, 0, 0, 0], [.17f, .48f, .93f, 1], 0, false, false);
                    frames[frame] = gl.Present(width, height, sampling, 0, static (_, _, _) => { }, true, true);
                    gl.QueuePresent(width, height, sampling, 0, static (_, _, _) => { }, true, true);
                    File.WriteAllBytes(Path.Combine(directory, $"cineform-geometry-{sampling}x-source-{frame}.png"), Png.Encode(frames[frame]));
                }
                // Both frames have been drawn before reading either PBO. A reused
                // resolve surface must not replace earlier queued image contents.
                foreach (var expected in frames)
                    Check(gl.ReadQueued().Rgba.SequenceEqual(expected.Rgba),
                        $"{sampling}x raw-video queue retains exact resolved RGBA and frame order after another draw");
                Check(gl.PendingPixels == 0, $"{sampling}x export drains its complete pixel queue");
                geometry.Add(sampling, frames);
            }
            Check(geometry[1].Sum(PartialEdges) == 0 && geometry[4].Sum(PartialEdges) > 100,
                "4x native supersampling creates fractional coverage before any encoder runs");
            Compare("geometry", geometry[1], geometry[4], directory, ffmpeg, comparisons, Check);

            // These are generated by the same-run real Cubism test, with identical
            // evaluated model, pose and output grid, before any video encoder runs.
            var model1 = Png.Decode(File.ReadAllBytes(Path.Combine(directory, "model-quality-1x.png")));
            var model4 = Png.Decode(File.ReadAllBytes(Path.Combine(directory, "model-quality-4x-reference.png")));
            Check(model1.Width == model4.Width && model1.Height == model4.Height && Error(model1, model4) > 0,
                "Real model comparison uses distinct 1x/4x native images on the same output grid");
            Compare("model", [model1], [model4], directory, ffmpeg, comparisons, Check);
            report["ok"] = true;
            Console.WriteLine($"Passed {checks.Count} actual native AA and decoded CineForm pixel checks."); return 0;
        }
        catch (Exception error) { report["exception"] = error.ToString(); throw; }
        finally { File.WriteAllText(Path.Combine(directory, "cineform-quality-report.json"), report.ToJsonString(new() { WriteIndented = true })); }
    }

    static void Compare(string subject, Pixels[] single, Pixels[] sampled, string directory, string ffmpeg,
        JsonArray comparisons, Action<bool, string> check)
    {
        int width = sampled[0].Width, height = sampled[0].Height;
        double samplingError = single.Zip(sampled, Error).Average(); double? film1Error = null;
        foreach (var (sampling, quality, images) in new[] { (1, "film1", single), (4, "film1", sampled), (4, "film3+", sampled) })
        {
            string name = $"cineform-{subject}-{sampling}x-{quality}", movie = Path.Combine(directory, name + ".mov");
            using (var encoder = Process.Start(VideoEncoding.RawVideoStartInfo(ffmpeg, "cineform", width, height, 30, movie, quality))
                ?? throw new IOException("Cannot start the CineForm encoder."))
            {
                var stderr = encoder.StandardError.ReadToEndAsync();
                foreach (var image in images)
                    for (int y = 0; y < image.Height; y++) encoder.StandardInput.BaseStream.Write(image.GetRgbaRow(y));
                encoder.StandardInput.Close(); encoder.WaitForExit();
                if (encoder.ExitCode != 0) throw VideoEncoding.EncoderFailure(encoder.ExitCode, stderr.GetAwaiter().GetResult());
                _ = stderr.GetAwaiter().GetResult();
            }
            byte[] decodedBytes = Decode(ffmpeg, movie);
            int frameBytes = checked(width * height * 4);
            check(decodedBytes.Length == checked(frameBytes * images.Length), $"{name}: actual decoded frame count matches submitted RGBA frames");
            var decoded = new Pixels[images.Length]; var hashes = new JsonArray();
            int alphaError = 0, edges = 0, retained = 0;
            for (int frame = 0; frame < images.Length; frame++)
            {
                decoded[frame] = new(width, height, decodedBytes.AsSpan(frame * frameBytes, frameBytes).ToArray());
                File.WriteAllBytes(Path.Combine(directory, $"{name}-decoded-{frame}.png"), Png.Encode(decoded[frame]));
                byte[] original = images[frame].Rgba, result = decoded[frame].Rgba;
                for (int i = 3; i < original.Length; i += 4)
                {
                    alphaError = Math.Max(alphaError, Math.Abs(original[i] - result[i]));
                    if (original[i] is >= 16 and <= 239)
                    {
                        edges++; if (result[i] is > 0 and < 255) retained++;
                    }
                }
                hashes.Add((JsonNode)new JsonObject { ["frame"] = frame,
                    ["source"] = Convert.ToHexString(SHA256.HashData(original)),
                    ["decoded"] = Convert.ToHexString(SHA256.HashData(result)) });
            }
            double codecError = images.Zip(decoded, Error).Average();
            comparisons.Add((JsonNode)new JsonObject { ["subject"] = subject, ["supersample"] = sampling,
                ["quality"] = quality, ["width"] = width, ["height"] = height, ["frames"] = images.Length,
                ["sampling1xTo4xMse"] = samplingError, ["codecRoundTripMse"] = codecError,
                ["decodedTo4xMse"] = decoded.Zip(sampled, Error).Average(), ["maximumAlphaError"] = alphaError,
                ["fractionalEdgePixels"] = edges, ["retainedFractionalEdgePixels"] = retained,
                ["movieBytes"] = new FileInfo(movie).Length, ["hashes"] = hashes });
            check(alphaError <= 8, $"{name}: decoded alpha stays within eight RGBA8 levels of the pre-encode image");
            if (sampling == 1) continue;
            check(edges > 20 && retained >= edges * .98, $"{name}: decoded CineForm retains the real antialiased fractional edges");
            check(codecError < samplingError * .1,
                $"{name}: measured codec loss is less than one tenth of the actual 1x-to-4x sampling difference");
            if (quality == "film1") film1Error = codecError;
            else check(film1Error is { } lowerQualityError && codecError <= lowerQualityError,
                $"{name}: highest CineForm quality reduces or preserves measured RGBA error without changing sampling");
        }
    }

    static byte[] Decode(string ffmpeg, string movie)
    {
        var start = new ProcessStartInfo(ffmpeg) { UseShellExecute = false, CreateNoWindow = true,
            RedirectStandardOutput = true, RedirectStandardError = true };
        foreach (string argument in new[] { "-v", "error", "-nostdin", "-i", movie, "-map", "0:v:0", "-pix_fmt", "rgba", "-f", "rawvideo", "pipe:1" })
            start.ArgumentList.Add(argument);
        using var decoder = Process.Start(start) ?? throw new IOException("Cannot start the CineForm decoder.");
        var stderr = decoder.StandardError.ReadToEndAsync(); using var output = new MemoryStream();
        decoder.StandardOutput.BaseStream.CopyTo(output); decoder.WaitForExit();
        string details = stderr.GetAwaiter().GetResult();
        if (decoder.ExitCode != 0) throw new IOException($"FFmpeg video decoder exited with code {decoder.ExitCode}. {details}");
        return output.ToArray();
    }

    static int PartialEdges(Pixels image)
    {
        int count = 0; for (int i = 3; i < image.Rgba.Length; i += 4) if (image.Rgba[i] is > 0 and < 255) count++;
        return count;
    }

    static double Error(Pixels image, Pixels reference)
    {
        if (image.Width != reference.Width || image.Height != reference.Height) throw new ArgumentException("Matching pixel grids are required.");
        double sum = 0;
        for (int i = 0; i < image.Rgba.Length; i += 4)
        {
            double a = image.Rgba[i + 3] / 255d, b = reference.Rgba[i + 3] / 255d;
            for (int c = 0; c < 3; c++) { double difference = image.Rgba[i + c] * a - reference.Rgba[i + c] * b; sum += difference * difference; }
            double alpha = image.Rgba[i + 3] - reference.Rgba[i + 3]; sum += alpha * alpha;
        }
        return sum / image.Rgba.Length;
    }
}
